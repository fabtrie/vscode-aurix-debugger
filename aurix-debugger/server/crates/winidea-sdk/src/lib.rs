//! Rust bindings for the iSYSTEM **winIDEA** SDK.
//!
//! # Which SDK this binds
//!
//! iSYSTEM ships three SDKs. This crate binds the **C#** one -- specifically its
//! native library `isystemConnect.dll` -- because it is the only one that
//! exposes a usable C ABI:
//!
//! | SDK | Shape | Usable from Rust? |
//! |---|---|---|
//! | C++ | 196 MB **static** lib, C++ classes, no `extern "C"` | no (see below) |
//! | Python | `.pyd` exporting only `PyInit__connect` | no -- needs CPython |
//! | **C#** | `isystemConnect.dll`, **6,094 flat `extern "C"` exports** | **yes** |
//!
//! SWIG's C# backend emits a plain C wrapper per method, so the DLL is a
//! conventional dynamic library: we load it with `libloading` at runtime, the
//! same way `vector-driver` loads `vxlapi64.dll`. It has **no .NET/CLR
//! dependency** (only MSVCP140/VCRUNTIME140/WS2_32).
//!
//! The C++ SDK cannot give full coverage even with a hand-written shim: it ships
//! headers for only 76 classes (vs 451 here), and the DAQ data types
//! (`CDAQSample`, `CDAQStatus`) have their accessors defined `inline` in headers
//! that were never shipped -- so they have *zero* linkable symbols in the static
//! lib. Those same accessors are ordinary exports in this DLL.
//!
//! # How the bindings are produced
//!
//! `src/generated/ffi.rs` is generated by `tools/generate_rust.py` from the
//! P/Invoke metadata inside the managed `IConnectCSLib.dll`. Every signature is
//! what the DLL was compiled with -- none of it is inferred from documentation
//! or guessed from mangled names. Regenerate with:
//!
//! ```text
//! ildasm /TEXT /NOBAR IConnectCSLib.dll > tools/csil.txt
//! dumpbin /EXPORTS isystemConnect.dll   > tools/csexp.txt
//! uv run --script tools/extract_pinvoke.py tools/csil.txt tools/csexp.txt tools/pinvoke.json
//! uv run --script tools/generate_rust.py   tools/pinvoke.json src/generated/ffi.rs
//! ```
//!
//! # Status
//!
//! The raw FFI layer covers all 6,094 exports. Safe wrappers cover connection
//! ([`connection`]), execution ([`execution`]), debug/expression evaluation
//! ([`debug`]), symbol lookup ([`address`]), bulk memory + symbol enumeration
//! ([`data`]), the IDE ([`ide`]) and DAQ ([`daq`]). Everything else is reachable
//! through [`WinIdea::raw`].
//!
//! Verified against a real winIDEA + target, including a full DAQ acquisition
//! cycle -- see `examples/smoke.rs`.
//!
//! # Version tolerance
//!
//! These bindings are generated from the 9.21.417 SDK, but the DLL is loaded
//! **tolerantly**: exports it does not provide bind as `None` (listed by
//! `Sdk::missing`) instead of aborting the load. Calling into one yields
//! [`Error::MissingSymbol`], naming the export.
//!
//! This matters because the export set genuinely differs between winIDEA
//! versions -- 9.21.417 introduced the entire `CDAQConfig` family (DAQ
//! acquisition modes), which 9.21.356 has no trace of. Resolving every symbol
//! eagerly meant one absent export failed the whole connection with an
//! unattributed `GetProcAddress failed`.
//!
//! Point [`WinIdea::open_at`] (or the `AURIX_WINIDEA_SDK_PATH` env var) at a
//! DLL matching the winIDEA in use for the best coverage.

/// Call an SDK export, or fail naming it.
///
/// Every export is `Option`, since a given DLL may not provide it. This keeps
/// the call sites reading like the raw FFI they wrap while turning an absent
/// export into a proper error instead of a panic.
///
/// ```ignore
/// let n = unsafe { sym!(sdk, IntVector_size)(handles.ptr) };
/// ```
#[macro_export]
macro_rules! sym {
    ($sdk:expr, $name:ident) => {
        $sdk.$name
            .ok_or($crate::Error::MissingSymbol(stringify!($name)))?
    };
}

