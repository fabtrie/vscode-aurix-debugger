impl WinIdea {
    /// Direct access to the raw, unsafe FFI surface.
    ///
    /// Use this for the parts of the SDK that do not have a safe wrapper yet.
    /// Callers are responsible for handle validity and for calling
    /// [`WinIdea::take_error`] after each call that can fail.
    pub fn raw(&self) -> &generated::ffi::Sdk {
        &self.sdk
    }

    /// Take the pending SDK exception, if the last call raised one.
    ///
    /// The native library never unwinds across the ABI: it reports failures by
    /// invoking a callback, and the host checks afterwards. Safe wrappers do
    /// this automatically; callers using [`WinIdea::raw`] must do it themselves.
    pub fn take_error(&self) -> Result<(), Error> {
        runtime::check()
    }
}
